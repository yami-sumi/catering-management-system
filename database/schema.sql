
-- =========================================
-- CATERING BUSINESS MANAGEMENT SYSTEM
-- Database: catering_management_db
-- PostgreSQL 18.6
-- =========================================

-- 1. CUSTOMER
CREATE TABLE customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone VARCHAR(20),
    address VARCHAR(255),
    password_hash TEXT
);

-- 2. PACKAGE
CREATE TABLE package (
    package_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    price_per_guest NUMERIC(10,2) NOT NULL
        CHECK (price_per_guest >= 0)
);

-- 3. MENU_ITEM
CREATE TABLE menu_item (
    menu_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(100) NOT NULL,
    description TEXT,
    category VARCHAR(50) NOT NULL,
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0)
);

-- 4. EMPLOYEE
CREATE TABLE employee (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    role VARCHAR(50) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(100)
);

-- 5. INVENTORY
CREATE TABLE inventory (
    inventory_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(100) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    quantity INTEGER NOT NULL
        CHECK (quantity >= 0),
    availability_status VARCHAR(30) NOT NULL DEFAULT 'Available'
);

-- 6. RESERVATION
CREATE TABLE reservation (
    reservation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    package_id INTEGER NOT NULL,
    event_date DATE NOT NULL,
    venue VARCHAR(255) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    number_of_guests INTEGER NOT NULL
        CHECK (number_of_guests > 0),
    status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    estimated_cost NUMERIC(10,2),

    CONSTRAINT fk_reservation_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(customer_id),

    CONSTRAINT fk_reservation_package
        FOREIGN KEY (package_id)
        REFERENCES package(package_id)
);

-- 7. PAYMENT
CREATE TABLE payment (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id INTEGER NOT NULL,
    payment_amount NUMERIC(10,2) NOT NULL
        CHECK (payment_amount > 0),
    payment_date DATE NOT NULL,
    payment_status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    payment_method VARCHAR(40),
    reference_number VARCHAR(100),

    CONSTRAINT fk_payment_reservation
        FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id)
);

-- 8. RESERVATION_MENU
CREATE TABLE reservation_menu (
    reservation_id INTEGER NOT NULL,
    menu_item_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL
        CHECK (quantity > 0),

    PRIMARY KEY (reservation_id, menu_item_id),

    FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id),

    FOREIGN KEY (menu_item_id)
        REFERENCES menu_item(menu_item_id)
);

-- 9. EVENT_ASSIGNMENT
CREATE TABLE event_assignment (
    reservation_id INTEGER NOT NULL,
    employee_id INTEGER NOT NULL,
    assignment_role VARCHAR(50) NOT NULL,

    PRIMARY KEY (reservation_id, employee_id),

    FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id),

    FOREIGN KEY (employee_id)
        REFERENCES employee(employee_id)
);

-- 10. CANCELLATION
CREATE TABLE cancellation (
    cancellation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id INTEGER NOT NULL,
    cancellation_date DATE NOT NULL,
    cancellation_reason VARCHAR(255),
    cancellation_fee NUMERIC(10,2),
    refund_amount NUMERIC(10,2),
    cancellation_status VARCHAR(20) NOT NULL DEFAULT 'Pending',

    CONSTRAINT fk_cancellation_reservation
        FOREIGN KEY (reservation_id)
        REFERENCES reservation(reservation_id),

    CONSTRAINT chk_cancellation_fee
        CHECK (cancellation_fee IS NULL OR cancellation_fee >= 0),

    CONSTRAINT chk_refund_amount
        CHECK (refund_amount IS NULL OR refund_amount >= 0)
);

-- 11. ADMIN
CREATE TABLE IF NOT EXISTS admin (
    admin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);